%% ВИВІД РІВНЯННЯ (29) НА ОСНОВІ angles_ned.mlx
% =========================================================================
% Призначення файла
% =========================================================================
% Цей скрипт формує символічний аналог рівняння (29) з конспекту лекції.
%
% У вихідному файлі angles_ned.mlx:
%
%   1) використовується навігаційна система координат NED:
%        n = [North; East; Down];
%
%   2) матриця D переводить координати вектора з NED у зв'язану
%      з літальним апаратом систему координат body:
%
%        vector_b = D * vector_n;
%
%   3) зворотне перетворення body -> NED виконується через:
%
%        vector_n = D.' * vector_b;
%
%   4) рівняння поступального руху у body записується у вигляді:
%
%        m*dV_b/dt + omega_b x (m*V_b) = F_b.
%
% Для отримання рівняння (29) необхідно:
%
%   1) перейти від компонент швидкості [u;v;w] до параметрів траєкторії
%      V_k, Theta, Psi;
%
%   2) побудувати матрицю NED -> trajectory;
%
%   3) замінити тягу мультикоптера вздовж -Z_b на тягу ракети вздовж +X_b;
%
%   4) додати аеродинамічні сили [-Q;Y_a;Z_a];
%
%   5) спроєктувати всі сили на осі траєкторної системи координат;
%
%   6) прирівняти проєкції сил до:
%
%        [ m*V_k_dot;
%          m*V_k*Theta_dot;
%         -m*V_k*cos(Theta)*Psi_dot ].
%
% =========================================================================
% Умовні позначення систем координат
% =========================================================================
%
% n — NED:
%       X_n = North;
%       Y_n = East;
%       Z_n = Down.
%
% b — зв'язана система координат ракети:
%       X_b — уздовж поздовжньої осі ракети вперед;
%       Y_b — поперечна вісь згідно з домовленістю angles_ned.mlx;
%       Z_b — третя вісь зв'язаної системи.
%
% k — траєкторна система координат:
%       X_k — уздовж вектора земної швидкості;
%       Y_k — у вертикальній площині траєкторії;
%       Z_k — поперечна вісь траєкторної системи.
%
% a — швидкісна аеродинамічна система:
%       X_a — уздовж вектора повітряної швидкості;
%       Y_a — уздовж підйомної сили;
%       Z_a — уздовж бокової сили.
%
% =========================================================================
% Правило позначення матриць
% =========================================================================
%
% Матриця C_x_y переводить координати вектора із системи y у систему x:
%
%       vector_x = C_x_y * vector_y.
%
% Наприклад:
%
%       C_b_n = D
%
% означає перехід NED -> body.
%
% Оскільки матриці повороту ортогональні:
%
%       C_n_b = C_b_n.'.
%
% =========================================================================

clear
clc

%% 1. Символьні змінні з вихідного файла angles_ned.mlx
% -------------------------------------------------------------------------
% phi — кут крену корпусу, roll;
% theta — кут тангажу корпусу, pitch;
% psi — кут рискання корпусу, yaw;
%
% u — компонента швидкості вздовж осі X_b;
% v — компонента швидкості вздовж осі Y_b;
% w — компонента швидкості вздовж осі Z_b;
%
% p — кутова швидкість навколо X_b;
% q — кутова швидкість навколо Y_b;
% r — кутова швидкість навколо Z_b;
%
% u_dot, v_dot, w_dot — похідні компонент швидкості у body;
%
% m — маса ракети;
% g — прискорення вільного падіння.

syms phi theta psi real
syms u v w real
syms u_dot v_dot w_dot real
syms p q r real
syms m g real

%% 2. Додаткові змінні для рівняння (29)
% -------------------------------------------------------------------------
% V_k — модуль земної швидкості ракети.
%
% Theta — кут нахилу траєкторії.
% Це кут між вектором земної швидкості та горизонтальною площиною.
% Додатний Theta відповідає набору висоти.
%
% Psi — шляховий кут у позначеннях конспекту.
% У прийнятій тут відповідності зі стандартним NED-курсом chi:
%
%       Psi = -chi.
%
% V_k_dot — похідна модуля земної швидкості;
% Theta_dot — похідна кута нахилу траєкторії;
% Psi_dot — похідна шляхового кута;
%
% P — сила тяги ракети.
% Вектор тяги спрямований уздовж додатної осі X_b.
%
% Q — додатний модуль сили лобового опору.
% У швидкісній системі її компонента вздовж X_a дорівнює -Q.
%
% Y_a — підйомна аеродинамічна сила.
%
% Z_a — бокова аеродинамічна сила.
%
% vartheta_a — швидкісний кут тангажу.
% Визначає вертикальний нахил вектора повітряної швидкості.
%
% psi_a — швидкісний кут рискання.
% Визначає напрям горизонтальної проєкції повітряної швидкості.
%
% gamma_a — швидкісний кут крену.
% Визначає поворот осей Y_a, Z_a навколо вектора повітряної швидкості.

syms V_k Theta Psi real
syms V_k_dot Theta_dot Psi_dot real
syms vartheta_a psi_a gamma_a real
syms P Q Y_a Z_a real

%% 3. Елементарна матриця повороту навколо осі X angles_ned.mlx.
% -------------------------------------------------------------------------
% R_x_phi виконує пасивне перетворення координат при повороті системи
% координат на кут phi навколо осі X.

R_x_phi = [1,          0,           0;
           0,  cos(phi),    sin(phi);
           0, -sin(phi),    cos(phi)];

%% 4. Елементарна матриця повороту навколо осі Y angles_ned.mlx.
% -------------------------------------------------------------------------
% R_y_theta виконує пасивне перетворення координат при повороті системи
% координат на кут theta навколо осі Y.

R_y_theta = [ cos(theta), 0, -sin(theta);
                       0, 1,           0;
              sin(theta), 0,  cos(theta)];

%% 5. Елементарна матриця повороту навколо осі Z angles_ned.mlx.
% -------------------------------------------------------------------------
% R_z_psi виконує пасивне перетворення координат при повороті системи
% координат на кут psi навколо осі Z.

R_z_psi = [ cos(psi),  sin(psi), 0;
           -sin(psi),  cos(psi), 0;
                   0,         0, 1];

%% 6. Матриця переходу NED -> body angles_ned.mlx
% -------------------------------------------------------------------------
%
%       D = R_x_phi * R_y_theta * R_z_psi 
%

%
%       vector_b = D * vector_n.
%

D = simplify(R_x_phi * R_y_theta * R_z_psi);
C_b_n = D;

%% 7. Матриця переходу body -> NED angles_ned.mlx
% -------------------------------------------------------------------------
% Матриця D ортогональна, тому обернена матриця дорівнює транспонованій:
%
%       inv(D) = D.'.
%       vector_n = D.' * vector_b.
%
%__________________________________________________________________________ Це перетворення перевірити, використано для тяги ракети, яка задана у body.

C_n_b = simplify(C_b_n.');

%% 8. Вектор лінійної швидкості у body angles_ned.mlx
% -------------------------------------------------------------------------
V_b = [u;
       v;
       w];

%% 9. Вектор кутової швидкості у body angles_ned.mlx
% -------------------------------------------------------------------------
% Компоненти абсолютної кутової швидкості корпусу:
%
%       omega_b = [p;q;r].
omega_b = [p;
           q;
           r];

%% 10. Інерційна складова рівняння сил у body
% -------------------------------------------------------------------------
%       F_translation_b = m*dV_b/dt.

F_translation_b = m * [u_dot;
                         v_dot;
                         w_dot];

%% 11. Транспортний член у body angles_ned.mlx
% -------------------------------------------------------------------------
% Оскільки body обертається відносно NED, повна похідна вектора містить:
%
%                                                                          omega_b x (m*V_b)._________________________________________________!!!!
F_transport_b = cross(omega_b, m*V_b);% У angles_ned.mlx = rot_f.          F_transport_b - по факту кінеетична сила, через обертання базису 

%% 12. Повна рівнодійна сил у body
% -------------------------------------------------------------------------
% Результат:
%
%       F_required_b =
%           m*dV_b/dt + omega_b x (m*V_b).
%
% Права частина:
%
%       m*(du/dt + q*w - r*v);
%       m*(dv/dt + r*u - p*w);
%       m*(dw/dt + p*v - q*u).

F_required_b = simplify(F_translation_b + F_transport_b);                 

%% 13. Зв'язок body-рівняння з NED-рівнянням
% -------------------------------------------------------------------------
% Теорема про похідну вектора у рухомій системі дає:
%
%   D.' * [dV_b/dt + omega_b x V_b] = dV_n/dt.______________________________!
%   ПЕРЕВІРИТИ!
%
% Тому:
%
%       m*dV_n/dt = D.'*F_required_b.

% абсолютне прискорення, що переведено з зв'язаної системи координат в NED
a_n_from_body = simplify(C_n_b * (F_required_b/m));

%% 14. Вектор земної швидкості у NED через V_k, Theta і Psi                     !!!Перевірити, чому саме Psi = -chi??!!
% -------------------------------------------------------------------------
% У стандартній NED-системі зазвичай використовують курс chi:
%
%       V_N = V_k*cos(Theta)*cos(chi);
%       V_E = V_k*cos(Theta)*sin(chi);
%       V_D = -V_k*sin(Theta).
%
% У конспекті використано шляховий кут Psi з відповідністю:
%
%       Psi = -chi.                                                         
%
% Тоді:
%
%       cos(chi) = cos(Psi);
%       sin(chi) = -sin(Psi).
%
% Отже, вектор швидкості у NED:
%
%       V_n =
%       [ V_k*cos(Theta)*cos(Psi);
%        -V_k*cos(Theta)*sin(Psi);
%        -V_k*sin(Theta) ].                                                !!!ПТреба промалювати проекціцї вектора швидкості, щоб перевірити!!
% -------------------------------------------------------------------------
V_n = [ V_k*cos(Theta)*cos(Psi);
       -V_k*cos(Theta)*sin(Psi);
       -V_k*sin(Theta)];

%% 15. Матриця переходу NED -> trajectory
% -------------------------------------------------------------------------
% Матриця C_k_n переводить довільний вектор із NED у траєкторну систему:
%
%       vector_k = C_k_n * vector_n.
%
% Перший рядок — одиничний вектор осі X_k, тобто напрям швидкості.
%
% Другий рядок — одиничний вектор осі Y_k у вертикальній площині
% траєкторії.
%
% Третій рядок — одиничний вектор осі Z_k, поперечної до площини
% траєкторії.
%
% Матрицю побудовано так, щоб:
%
%       C_k_n * V_n = [V_k;0;0].

C_k_n = [ cos(Theta)*cos(Psi), -cos(Theta)*sin(Psi), -sin(Theta);% 
         -sin(Theta)*cos(Psi),  sin(Theta)*sin(Psi), -cos(Theta);%
                    sin(Psi),             cos(Psi),           0];%

C_k_n = simplify(C_k_n);

%% 16. Перевірка проєкції швидкості на траєкторні осі
% -------------------------------------------------------------------------
% Оскільки X_k збігається з напрямом V_n, результат повинен бути:
%
%       [V_k;0;0].
%
% Ця перевірка допомагає виявити помилку знаку в Psi або в матриці C_k_n.

V_k_components = simplify(C_k_n * V_n);

%% 17. Прискорення у NED
% -------------------------------------------------------------------------
% Повна похідна V_n за часом містить:
%
%   1) зміну модуля швидкості dV_k/dt;
%   2) зміну кута нахилу траєкторії dTheta/dt;
%   3) зміну шляхового кута dPsi/dt.

% Оскільки V_k, Theta і Psi задані як звичайні символи, похідну
% обчислюємо за правилом повної похідної:
%
%   dV_n/dt =
%       (∂V_n/∂V_k)*V_k_dot +
%       (∂V_n/∂Theta)*Theta_dot +
%       (∂V_n/∂Psi)*Psi_dot.
%
% У матричному вигляді це добуток якобіана на вектор похідних.

% % 
% % % Вектор швидкості у NED
% % V_n = [ V_k*cos(Theta)*cos(Psi);
% %        -V_k*cos(Theta)*sin(Psi);
% %        -V_k*sin(Theta)];
% % 
% % % Змінні, від яких залежить V_n
% % trajectory_variables = [V_k, Theta, Psi];
% % 
% % % Їхні похідні за часом
% % trajectory_derivatives = [V_k_dot;
% %                           Theta_dot;
% %                           Psi_dot];
% % 
% % % Якобіан швидкості у NED
% % J_V = jacobian(V_n, trajectory_variables);
% % 
% % % Повна похідна швидкості, тобто прискорення у NED
% % a_n = simplify(J_V * trajectory_derivatives, ...
% %                'Steps', 100);
% % 
% % % Перехід NED -> trajectory
% % a_k = simplify(C_k_n * a_n, ...
% %                'Steps', 200);


trajectory_variables = [V_k, Theta, Psi];
trajectory_derivatives = [V_k_dot;
                          Theta_dot;
                          Psi_dot];

a_n = simplify( ...
    jacobian(V_n, trajectory_variables) * trajectory_derivatives, ...
    'Steps', 100);

%% 18. Прискорення у траєкторній системі
% -------------------------------------------------------------------------
% Перехід NED -> trajectory:
%
%       a_k = C_k_n * a_n.
%
% Після спрощення очікується:
%
%       a_k =
%       [ dV_k/dt;
%         V_k*dTheta/dt;
%        -V_k*cos(Theta)*dPsi/dt ].
%
% Саме цей вектор формує ліву частину рівняння (29).

a_k_from_derivative = trigSimplifyR2022( ...
    C_k_n * a_n, 200);

%% 19. Явно задана очікувана ліва частина рівняння (29)
% -------------------------------------------------------------------------
% Цей вектор задається окремо для зручності порівняння та формування
% символьних рівнянь.

a_k_expected = [ V_k_dot;
                 V_k*Theta_dot;
                -V_k*cos(Theta)*Psi_dot];

%% 20. Перевірка лівої частини
% -------------------------------------------------------------------------
% Різниця між отриманим і очікуваним прискоренням повинна бути:
%
%       [0;0;0].

check_acceleration = trigSimplifyR2022( ...
    a_k_from_derivative - a_k_expected, 200);

%% 21. Вектор тяги ракети у body
% -------------------------------------------------------------------------%
% Для ракети з рівняння (29) тяга спрямована вздовж +X_b:
%
%       F_P_b = [P;0;0].
%

F_P_b = [P;
         0;
         0];

%% 22. Перетворення тяги body -> NED
% -------------------------------------------------------------------------
% Вектор тяги заданий у body.
%
% Матриця C_n_b = D.' виконує перехід:
%
%       body -> NED.
%
% Тому:
%
%       F_P_n = C_n_b * F_P_b.

F_P_n = simplify(C_n_b * F_P_b);

%% 23. Перетворення тяги NED -> trajectory
% -------------------------------------------------------------------------
% Після отримання NED-компонент тяги виконуємо:
%
%       F_P_k = C_k_n * F_P_n.
%
% Складене перетворення:
%
%       F_P_k = C_k_n * C_n_b * F_P_b.
%
% Добуток C_k_n*C_n_b є матрицею body -> trajectory.

C_k_b = simplify(C_k_n * C_n_b);
F_P_k = simplify(expand(C_k_b * F_P_b), 'Steps', 200);

%% 24. Вектор сили ваги у NED
% -------------------------------------------------------------------------
% У системі NED вісь Z_n спрямована вниз.
%
% Тому сила ваги має додатну третю компоненту:
%
%       F_G_n = [0;0;m*g].

F_G_n = [0;
         0;
         m*g];

%% 25. Перетворення сили ваги NED -> trajectory
% -------------------------------------------------------------------------
% Оскільки сила ваги вже задана у NED, потрібен лише один перехід:
%
%       F_G_k = C_k_n * F_G_n.
%
% Очікувані компоненти:
%
%       [-m*g*sin(Theta);
%        -m*g*cos(Theta);
%         0].

F_G_k = simplify(C_k_n * F_G_n);

%% 26. Елементарна швидкісна матриця повороту навколо X
% -------------------------------------------------------------------------
% R_x_gamma_a задає поворот швидкісної системи навколо осі X_a,
% спрямованої вздовж вектора повітряної швидкості.
%
% Кут gamma_a — швидкісний кут крену.
% кут повороту швидкісної системи координат навколо її поздовжньої осі, яка збігається з напрямком вектора повітряної швидкості 

R_x_gamma_a = [1,                0,                 0;
               0,     cos(gamma_a),      sin(gamma_a);
               0,    -sin(gamma_a),      cos(gamma_a)];

%% 27. Елементарна швидкісна матриця повороту навколо Y
% -------------------------------------------------------------------------
% R_y_vartheta_a задає швидкісний кут тангажу vartheta_a.
%
% Він визначає вертикальний нахил вектора повітряної швидкості.

R_y_vartheta_a = [ cos(vartheta_a), 0, -sin(vartheta_a);
                                  0, 1,                 0;
                   sin(vartheta_a), 0,  cos(vartheta_a)];

%% 28. Елементарна швидкісна матриця повороту навколо Z
% -------------------------------------------------------------------------
% R_z_psi_a задає швидкісний кут рискання psi_a.
%
% Він визначає азимутальний напрям вектора повітряної швидкості.

R_z_psi_a = [ cos(psi_a),  sin(psi_a), 0;
             -sin(psi_a),  cos(psi_a), 0;
                       0,           0, 1];

%% 29. Матриця переходу NED -> швидкісну
% -------------------------------------------------------------------------
% Для узгодження з порядком матриць angles_ned.mlx використано:
%
%       D_a = R_x_gamma_a * R_y_vartheta_a * R_z_psi_a.
%
% Фізичний зміст:
%
%       vector_a = D_a * vector_n.
%
% Позначимо:
%
%       C_a_n = D_a.

D_a = simplify( ...
    R_x_gamma_a * R_y_vartheta_a * R_z_psi_a);

C_a_n = D_a;

%% 30. Матриця переходу aerodynamic -> NED
% -------------------------------------------------------------------------
% Зворотний перехід виконується транспонуванням:
%
%       vector_n = C_a_n.' * vector_a.

C_n_a = simplify(C_a_n.');

%% 31. Вектор аеродинамічних сил у швидкісній системі
% -------------------------------------------------------------------------
% У швидкісній системі:
%
%       -Q  — сила лобового опору проти осі +X_a;
%        Y_a — підйомна сила вздовж +Y_a;
%        Z_a — бокова сила вздовж +Z_a.
%
% Тому:
%
%       F_A_a = [-Q;Y_a;Z_a].

F_A_a = [-Q;
          Y_a;
          Z_a];

%% 32. Перетворення аеродинамічної сили aerodynamic -> NED
% -------------------------------------------------------------------------
% Початковий вектор задано у системі a.
%
% Перехід:
%
%       F_A_n = C_n_a * F_A_a.

F_A_n = simplify(C_n_a * F_A_a);

%% 33. Перетворення аеродинамічної сили NED -> trajectory
% -------------------------------------------------------------------------
% Другий перехід:
%
%       F_A_k = C_k_n * F_A_n.
%
% Разом:
%
%       F_A_k = C_k_n * C_n_a * F_A_a.
%
% Добуток C_k_n*C_n_a є матрицею aerodynamic -> trajectory.

C_k_a = simplify(C_k_n * C_n_a);
F_A_k = simplify(expand(C_k_a * F_A_a), 'Steps', 300);

%% 34. Сума всіх зовнішніх сил у trajectory
% -------------------------------------------------------------------------
% Після переведення всіх сил в одну систему координат їх можна складати:
%
%       F_total_k = F_P_k + F_G_k + F_A_k.
%
% Компоненти:
%
%       F_total_k(1) = F_xk;
%       F_total_k(2) = F_yk;
%       F_total_k(3) = F_zk.

F_total_k = simplify( ...
    expand(F_P_k + F_G_k + F_A_k), ...
    'Steps', 400);

%% 35. Формування рівняння (29)
% -------------------------------------------------------------------------
% Другий закон Ньютона у траєкторній системі:
%
%       m*a_k_expected = F_total_k.
%
% Покомпонентно:
%
%       m*dV_k/dt =
%           F_P_xk + F_G_xk + F_A_xk;
%
%       m*V_k*dTheta/dt =
%           F_P_yk + F_G_yk + F_A_yk;
%
%      -m*V_k*cos(Theta)*dPsi/dt =
%           F_P_zk + F_G_zk + F_A_zk.
%
% Ці три рівняння є компактною матричною формою рівняння (29).

eq29 = [m*a_k_expected(1) == F_total_k(1);
        m*a_k_expected(2) == F_total_k(2);
        m*a_k_expected(3) == F_total_k(3)];

%% 36. Групування правих частин за фізичними силами
% -------------------------------------------------------------------------
% expand(...) розкриває всі добутки.
%
% collect(...,[P,Q,Y_a,Z_a]) групує доданки за:
%
%       P   — тягою;
%       Q   — лобовим опором;
%       Y_a — підйомною силою;
%       Z_a — боковою силою.
%
% Це полегшує порівняння результату з друкованою формулою (29).

rhs29_1 = collect( ...
    expand(F_total_k(1)), ...
    [P,Q,Y_a,Z_a]);

rhs29_2 = collect( ...
    expand(F_total_k(2)), ...
    [P,Q,Y_a,Z_a]);

rhs29_3 = collect( ...
    expand(F_total_k(3)), ...
    [P,Q,Y_a,Z_a]);

%% 37. Матриця коефіцієнтів при силах
% -------------------------------------------------------------------------
% Результуючу силу можна записати:
%
%       F_total_k =
%           A_force*[P;Q;Y_a;Z_a] + F_G_k.
%
% Стовпці A_force:
%
%       1 — коефіцієнти при P;
%       2 — коефіцієнти при Q;
%       3 — коефіцієнти при Y_a;
%       4 — коефіцієнти при Z_a.
%
% Рядки:
%
%       1 — проєкція на X_k;
%       2 — проєкція на Y_k;
%       3 — проєкція на Z_k.

force_variables = [P,Q,Y_a,Z_a];
A_force = sym(zeros(3,4));

for row_index = 1:3
    for column_index = 1:4
        A_force(row_index,column_index) = simplify( ...
            diff(F_total_k(row_index), ...
                 force_variables(column_index)), ...
            'Steps', 150);
    end
end

%% 38. Виділення лише гравітаційних членів
% -------------------------------------------------------------------------
% Усі змінні сил P, Q, Y_a, Z_a формально прирівнюються до нуля.
%
% Отриманий вектор повинен збігатися з F_G_k.

gravity_terms = simplify( ...
    subs(F_total_k, ...
         force_variables, ...
         zeros(1,4)));

check_gravity_terms = simplify(gravity_terms - F_G_k);

%% 39. Перевірка ортогональності матриць
% -------------------------------------------------------------------------
% Для матриці напрямних косинусів повинно виконуватися:
%
%       C*C.' = I.
%
% Нульова матриця в результаті перевірки підтверджує ортогональність.

check_D_orthogonality = trigSimplifyR2022( ...
    C_b_n*C_b_n.' - eye(3), 200);

check_C_k_n_orthogonality = trigSimplifyR2022( ...
    C_k_n*C_k_n.' - eye(3), 200);

check_D_a_orthogonality = trigSimplifyR2022( ...
    C_a_n*C_a_n.' - eye(3), 200);

%% 40. Перевірка визначників матриць
% -------------------------------------------------------------------------
% Для правильної матриці обертання:
%
%       det(C) = +1.
%
% Значення -1 означало б відбиття, а не чистий поворот.

det_C_b_n = trigSimplifyR2022(det(C_b_n), 200);
det_C_k_n = trigSimplifyR2022(det(C_k_n), 200);
det_C_a_n = trigSimplifyR2022(det(C_a_n), 200);

