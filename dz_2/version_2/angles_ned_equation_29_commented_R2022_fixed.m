%% Локальна функція тригонометричного спрощення для MATLAB R2022
function result = trigSimplifyR2022(expression, numberOfSteps)
% trigSimplifyR2022 — спрощення символьного скаляра, вектора або матриці.
%
%
% Послідовність:
%   1. expand      — розкриття добутків і тригонометричних сум;
%   2. simplify    — загальне символьне спрощення;
%   3. combine     — спроба об'єднати тригонометричні доданки;
%   4. simplify    — остаточне спрощення.
%
% Функція сумісна з MATLAB R2022a та не використовує сторонні функції.

    if nargin < 2
        numberOfSteps = 100;
    end

    validateattributes(numberOfSteps, {'numeric'}, ...
        {'scalar','integer','positive'}, ...
        mfilename, 'numberOfSteps');

    result = expand(expression);
    result = simplify(result, 'Steps', numberOfSteps);

    % combine може залишити вираз без змін — це нормальна поведінка.
    result = combine(result, 'sincos');
    result = simplify(result, 'Steps', numberOfSteps);
end
