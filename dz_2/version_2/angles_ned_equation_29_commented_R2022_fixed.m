disp('==============================================================')
disp('Матриця NED -> body, C_b_n = D:')
pretty(C_b_n)

disp('Матриця body -> NED, C_n_b = D.'':')
pretty(C_n_b)

disp('Матриця NED -> trajectory, C_k_n:')
pretty(C_k_n)

disp('Матриця body -> trajectory, C_k_b:')
