%% ВИВІД РІВНЯННЯ (29) З ВИКОРИСТАННЯМ ПЕРЕТВОРЕНЬ ІЗ angles_ned.mlx
% =========================================================================
% Походження та призначення файла
% =========================================================================
% Побудова матриць повороту між навігаційною системою координат NED
% і зв'язаною з літальним апаратом системою координат запозичена з файла
% angles_ned.mlx.
%
% Із angles_ned.mlx використано:
%
%   1) навігаційну систему координат NED:
%
%          n = [North; East; Down];
%
%   2) елементарні матриці пасивного повороту навколо осей X, Y та Z;
%
%   3) порядок формування матриці переходу NED -> body:
%
%          C_b_n = R_x(phi)*R_y(theta)*R_z(psi);
%
%   4) правило зворотного переходу body -> NED:
%
%          C_n_b = C_b_n.';
%
%   5) загальний принцип подання векторів і сил у різних системах
%      координат через матриці напрямних косинусів.
%
% На основі цих перетворень у даному файлі виконується перехід до
% траєкторної форми рівнянь поступального руху ракети та формується
% система рівнянь, що відповідає рівнянню (29).
%
% =========================================================================
% Послідовність перетворень
% =========================================================================
% У скрипті використовується така послідовність обчислень.
%
%   1. Формується матриця переходу з NED у зв'язану систему координат:
%
%          vector_b = C_b_n*vector_n.
%
%   2. Транспонуванням отримується матриця зворотного переходу:
%
%          vector_n = C_n_b*vector_b,
%          C_n_b = C_b_n.'.
%
%   3. Вектор земної швидкості задається через траєкторні параметри:
%
%          V_k     — модуль земної швидкості;
%          Theta   — кут нахилу траєкторії;
%          Psi     — шляховий кут у прийнятій системі знаків.
%
%      У системі NED вектор швидкості має вигляд:
%
%          V_n = [ V_k*cos(Theta)*cos(Psi);
%                 -V_k*cos(Theta)*sin(Psi);
%                 -V_k*sin(Theta) ].
%
%   4. Формується матриця переходу NED -> trajectory:
%
%          vector_k = C_k_n*vector_n.
%
%      Вісь X_k спрямована вздовж вектора земної швидкості.
%
%   5. За допомогою якобіана обчислюється повна похідна V_n за часом:
%
%          a_n = dV_n/dt.
%
%   6. Прискорення переводиться з NED у траєкторну систему:
%
%          a_k = C_k_n*a_n.
%
%      У результаті отримуються компоненти:
%
%          a_k = [ V_k_dot;
%                  V_k*Theta_dot;
%                 -V_k*cos(Theta)*Psi_dot ].
%
%   7. Сила тяги задається у зв'язаній системі координат:
%
%          F_P_b = [P;0;0],
%
%      після чого виконується перехід:
%
%          body -> NED -> trajectory.
%
%      У складеному вигляді:
%
%          F_P_k = C_k_n*C_n_b*F_P_b.
%
%   8. Сила ваги задається безпосередньо в NED:
%
%          F_G_n = [0;0;m*g],
%
%      після чого переводиться у траєкторну систему:
%
%          F_G_k = C_k_n*F_G_n.
%
%   9. Аеродинамічна сила задається у швидкісній аеродинамічній системі:
%
%          F_A_a = [-Q;Y_a;Z_a].
%
%      Далі формується матриця NED -> aerodynamic і виконується перехід:
%
%          aerodynamic -> NED -> trajectory.
%
%      У складеному вигляді:
%
%          F_A_k = C_k_n*C_n_a*F_A_a.
%
%  10. Усі сили додаються в одній, траєкторній, системі координат:
%
%          F_total_k = F_P_k + F_G_k + F_A_k.
%
%  11. До кожної траєкторної компоненти застосовується другий закон
%      Ньютона:
%
%          m*a_k = F_total_k.
%
%      Отримані три скалярні рівняння формують систему рівняння (29).
%
% =========================================================================
% Умовні позначення систем координат
% =========================================================================
%
% n — локальна навігаційна система координат NED:
%
%       X_n — North, напрям на північ;
%       Y_n — East, напрям на схід;
%       Z_n — Down, вертикально вниз.
%
% b — зв'язана з ракетою система координат body:
%
%       X_b — поздовжня вісь ракети, спрямована вперед;
%       Y_b — поперечна вісь зв'язаної системи;
%       Z_b — третя вісь, що доповнює систему до правої трійки.
%
% k — траєкторна система координат trajectory:
%
%       X_k — спрямована вздовж вектора земної швидкості V_k;
%       Y_k — лежить у вертикальній площині траєкторії;
%       Z_k — поперечна до вертикальної площини траєкторії.
%
% a — швидкісна аеродинамічна система координат aerodynamic:
%
%       X_a — спрямована вздовж вектора повітряної швидкості;
%       Y_a — вісь, уздовж якої задається підйомна сила;
%       Z_a — вісь, уздовж якої задається бокова сила.
%
% =========================================================================
% Умовні позначення кутів
% =========================================================================
%
% phi       — кут крену зв'язаної системи, roll;
% theta     — кут тангажу зв'язаної системи, pitch;
% psi       — кут рискання зв'язаної системи, yaw;
%
% Theta     — кут нахилу траєкторії відносно горизонтальної площини;
%             додатний при русі вгору;
%
% Psi       — шляховий кут у позначеннях вихідного рівняння;
%             у прийнятій домовленості пов'язаний зі стандартним
%             NED-курсом chi співвідношенням Psi = -chi;
%
% vartheta_a — швидкісний кут тангажу;
% psi_a      — швидкісний кут рискання;
% gamma_a    — швидкісний кут крену.
%
% =========================================================================
% Умовні позначення кінематичних величин
% =========================================================================
%
% V_k       — модуль земної швидкості ракети;
% V_k_dot   — похідна модуля земної швидкості за часом;
% Theta_dot — похідна кута нахилу траєкторії за часом;
% Psi_dot   — похідна шляхового кута за часом;
%
% V_n       — вектор земної швидкості, поданий у NED;
% a_n       — вектор прискорення, поданий у NED;
% a_k       — вектор прискорення, поданий у траєкторній системі.
%
% =========================================================================
% Умовні позначення сил і параметрів
% =========================================================================
%
% m   — маса ракети;
% g   — прискорення вільного падіння;
% P   — сила тяги вздовж додатної осі X_b;
% Q   — додатний модуль сили лобового опору;
%       у швидкісній системі її компонента вздовж X_a дорівнює -Q;
% Y_a — підйомна аеродинамічна сила;
% Z_a — бокова аеродинамічна сила;
%
% F_P_b     — сила тяги у зв'язаній системі;
% F_P_n     — сила тяги у NED;
% F_P_k     — сила тяги у траєкторній системі;
% F_G_n     — сила ваги у NED;
% F_G_k     — сила ваги у траєкторній системі;
% F_A_a     — аеродинамічна сила у швидкісній системі;
% F_A_n     — аеродинамічна сила у NED;
% F_A_k     — аеродинамічна сила у траєкторній системі;
% F_total_k — сумарна зовнішня сила у траєкторній системі.
%
% =========================================================================
% Правило позначення матриць переходу
% =========================================================================
%
% Матриця C_x_y переводить координати вектора із системи y у систему x:
%
%       vector_x = C_x_y*vector_y.
%
% Приклади:
%
%       C_b_n — перехід NED -> body;
%       C_n_b — перехід body -> NED;
%       C_k_n — перехід NED -> trajectory;
%       C_k_b — перехід body -> trajectory;
%       C_a_n — перехід NED -> aerodynamic;
%       C_n_a — перехід aerodynamic -> NED;
%       C_k_a — перехід aerodynamic -> trajectory.
%
% Для ортогональної матриці напрямних косинусів зворотне перетворення
% отримується транспонуванням:
%
%       C_y_x = C_x_y.'.
%
% =========================================================================

clear
clc

%% 1. Символьні змінні з вихідного файла angles_ned.mlx
% -------------------------------------------------------------------------
% phi — кут крену корпусу, roll;
% theta — кут тангажу корпусу, pitch;
% psi — кут рискання корпусу, yaw;
%
% m — маса ракети;
% g — прискорення вільного падіння.

syms phi theta psi real
syms m g real

%% 2. Додаткові змінні для рівняння (29)
% -------------------------------------------------------------------------
% V_k — модуль земної швидкості ракети.
%
% Theta — кут нахилу траєкторії.
% Це кут між вектором земної швидкості та горизонтальною площиною.
% Додатний Theta відповідає набору висоти.
%
% Psi — шляховий кут у позначеннях конспекту.
% У прийнятій тут відповідності зі стандартним NED-курсом chi:
%
%       Psi = -chi.
%
% V_k_dot — похідна модуля земної швидкості;
% Theta_dot — похідна кута нахилу траєкторії;
% Psi_dot — похідна шляхового кута;
%
% P — сила тяги ракети.
% Вектор тяги спрямований уздовж додатної осі X_b.
%
% Q — додатний модуль сили лобового опору.
% У швидкісній системі її компонента вздовж X_a дорівнює -Q.
%
% Y_a — підйомна аеродинамічна сила.
%
% Z_a — бокова аеродинамічна сила.
%
% vartheta_a — швидкісний кут тангажу.
% Визначає вертикальний нахил вектора повітряної швидкості.
%
% psi_a — швидкісний кут рискання.
% Визначає напрям горизонтальної проєкції повітряної швидкості.
%
% gamma_a — швидкісний кут крену.
% Визначає поворот осей Y_a, Z_a навколо вектора повітряної швидкості.

syms V_k Theta Psi real
syms V_k_dot Theta_dot Psi_dot real
syms vartheta_a psi_a gamma_a real
syms P Q Y_a Z_a real

%% 3. Елементарна матриця повороту навколо осі X
% -------------------------------------------------------------------------
% R_x_phi виконує пасивне перетворення координат при повороті системи
% координат на кут phi навколо осі X.

R_x_phi = [1,          0,           0;
           0,  cos(phi),    sin(phi);
           0, -sin(phi),    cos(phi)];

%% 4. Елементарна матриця повороту навколо осі Y
% -------------------------------------------------------------------------
% R_y_theta виконує пасивне перетворення координат при повороті системи
% координат на кут theta навколо осі Y.

R_y_theta = [ cos(theta), 0, -sin(theta);
                       0, 1,           0;
              sin(theta), 0,  cos(theta)];

%% 5. Елементарна матриця повороту навколо осі Z
% -------------------------------------------------------------------------
% R_z_psi виконує пасивне перетворення координат при повороті системи
% координат на кут psi навколо осі Z.

R_z_psi = [ cos(psi),  sin(psi), 0;
           -sin(psi),  cos(psi), 0;
                   0,         0, 1];

%% 6. Матриця переходу NED -> body
% -------------------------------------------------------------------------
%
%       D = R_x_phi * R_y_theta * R_z_psi 
%

%
%       vector_b = D * vector_n.
%

D = simplify(R_x_phi * R_y_theta * R_z_psi);
C_b_n = D;

%% 7. Матриця переходу body -> NED
% -------------------------------------------------------------------------
% Матриця D ортогональна, тому обернена матриця дорівнює транспонованій:
%
%       inv(D) = D.'.
%       vector_n = D.' * vector_b.


C_n_b = simplify(C_b_n.');

%% 8. Вектор земної швидкості у NED через V_k, Theta і Psi
% -------------------------------------------------------------------------
% Стандартний шляховий кут chi у системі NED відлічують у горизонтальній
% площині від додатного напряму осі X_n = North до горизонтальної проєкції
% вектора швидкості. Додатний напрям відліку chi спрямований у бік осі
% Y_n = East, тобто за годинниковою стрілкою, якщо дивитися зверху.
%
% Для стандартного кута chi горизонтальні компоненти швидкості мають вигляд:
%
%       V_N = V_k*cos(Theta)*cos(chi);
%       V_E = V_k*cos(Theta)*sin(chi).
%
% У конспекті кут Psi відлічується від тієї самої осі X_n = North, але
% додатний напрям його відліку протилежний додатному напряму chi. Тобто:
%
%       chi > 0  — поворот від North у бік East;
%       Psi > 0  — поворот від North у протилежний бік.
%
% Через протилежні напрями відліку числові значення цих кутів для одного й
% того самого напряму горизонтальної проєкції швидкості мають протилежні
% знаки:
%
%       Psi = -chi,
%
% або, еквівалентно,
%
%       chi = -Psi.
%
% Підставимо chi = -Psi у стандартні формули NED:
%
%       V_N = V_k*cos(Theta)*cos(-Psi)
%           = V_k*cos(Theta)*cos(Psi),
%
% оскільки косинус є парною функцією:
%
%       cos(-Psi) = cos(Psi).
%
% Для східної компоненти:
%
%       V_E = V_k*cos(Theta)*sin(-Psi)
%           = -V_k*cos(Theta)*sin(Psi),
%
% оскільки синус є непарною функцією:
%
%       sin(-Psi) = -sin(Psi).
%
% Вертикальна компонента не залежить від шляхового кута. У системі NED
% вісь Z_n = Down спрямована вниз, а кут Theta вважається додатним під час
% набору висоти. Тому при Theta > 0 вертикальна компонента швидкості
% спрямована проти додатної осі Down і має від'ємний знак:
%
%       V_D = -V_k*sin(Theta).
%
% Отже, вектор земної швидкості у NED у позначеннях конспекту дорівнює:
%
%       V_n =
%       [  V_k*cos(Theta)*cos(Psi);
%         -V_k*cos(Theta)*sin(Psi);
%         -V_k*sin(Theta) ].
% -------------------------------------------------------------------------
V_n = [ V_k*cos(Theta)*cos(Psi);
       -V_k*cos(Theta)*sin(Psi);
       -V_k*sin(Theta)];

%% 9. Матриця переходу NED -> trajectory
% -------------------------------------------------------------------------
% Матриця C_k_n переводить довільний вектор із NED у траєкторну систему:
%
%       vector_k = C_k_n * vector_n.
%
% Перший рядок — одиничний вектор осі X_k, тобто напрям швидкості.
%
% Другий рядок — одиничний вектор осі Y_k у вертикальній площині
% траєкторії.
%
% Третій рядок — одиничний вектор осі Z_k, поперечної до площини
% траєкторії.
%
% Матрицю побудовано так, щоб:
%
%       C_k_n * V_n = [V_k;0;0].

C_k_n = [ cos(Theta)*cos(Psi), -cos(Theta)*sin(Psi), -sin(Theta);% 
         -sin(Theta)*cos(Psi),  sin(Theta)*sin(Psi), -cos(Theta);%
                    sin(Psi),             cos(Psi),           0];%

C_k_n = simplify(C_k_n);



%% 10. Прискорення у NED
% -------------------------------------------------------------------------
% Повна похідна V_n за часом містить:
%
%   1) зміну модуля швидкості dV_k/dt;
%   2) зміну кута нахилу траєкторії dTheta/dt;
%   3) зміну шляхового кута dPsi/dt.

% Оскільки V_k, Theta і Psi задані як звичайні символи, похідну
% обчислюємо за правилом повної похідної:
%
%   dV_n/dt =
%       (∂V_n/∂V_k)*V_k_dot +
%       (∂V_n/∂Theta)*Theta_dot +
%       (∂V_n/∂Psi)*Psi_dot.
%
% У матричному вигляді це добуток якобіана на вектор похідних.

% % 
% % % Їхні похідні за часом
% % trajectory_derivatives = [V_k_dot;
% %                           Theta_dot;
% %                           Psi_dot];
% % 
% % % Якобіан швидкості у NED
% % J_V = jacobian(V_n, trajectory_variables);
% % 
% % % Повна похідна швидкості, тобто прискорення у NED
% % a_n = simplify(J_V * trajectory_derivatives, ...
% %                'Steps', 100);
% % 
% % % Перехід NED -> trajectory
% % a_k = simplify(C_k_n * a_n, ...
% %                'Steps', 200);


trajectory_variables = [V_k, Theta, Psi];
trajectory_derivatives = [V_k_dot;
                          Theta_dot;
                          Psi_dot];

a_n = simplify( ...
    jacobian(V_n, trajectory_variables) * trajectory_derivatives, ...
    'Steps', 100);

%% 11. Прискорення у траєкторній системі
% -------------------------------------------------------------------------
% Перехід NED -> trajectory:
%
%       a_k = C_k_n * a_n.
%
% Після спрощення очікується:
%
%       a_k =
%       [ dV_k/dt;
%         V_k*dTheta/dt;
%        -V_k*cos(Theta)*dPsi/dt ].
%
% Саме цей вектор формує ліву частину рівняння (29).

a_k_from_derivative = trigSimplifyR2022( ...
    C_k_n * a_n, 200);

%% 12. Кінематична ліва частина рівняння (29)
% -------------------------------------------------------------------------
% Цей вектор задається окремо для зручності порівняння та формування
% символьних рівнянь.

a_k_expected = [ V_k_dot;
                 V_k*Theta_dot;
                -V_k*cos(Theta)*Psi_dot];

%% 13. Вектор тяги ракети у body
% -------------------------------------------------------------------------
% Для ракети з рівняння (29) тяга спрямована вздовж +X_b:
%
%       F_P_b = [P;0;0].
%

F_P_b = [P;
         0;
         0];

%% 14. Перетворення тяги body -> NED
% -------------------------------------------------------------------------
% Вектор тяги заданий у body.
%
% Матриця C_n_b = D.' виконує перехід:
%
%       body -> NED.
%
% Тому:
%
%       F_P_n = C_n_b * F_P_b.

F_P_n = simplify(C_n_b * F_P_b);

%% 15. Перетворення тяги NED -> trajectory
% -------------------------------------------------------------------------
% Після отримання NED-компонент тяги виконуємо:
%
%       F_P_k = C_k_n * F_P_n.
%
% Складене перетворення:
%
%       F_P_k = C_k_n * C_n_b * F_P_b.
%
% Добуток C_k_n*C_n_b є матрицею body -> trajectory.

C_k_b = simplify(C_k_n * C_n_b);
F_P_k = simplify(expand(C_k_b * F_P_b), 'Steps', 200);

%% 16. Вектор сили ваги у NED
% -------------------------------------------------------------------------
% У системі NED вісь Z_n спрямована вниз.
%
% Тому сила ваги має додатну третю компоненту:
%
%       F_G_n = [0;0;m*g].

F_G_n = [0;
         0;
         m*g];

%% 17. Перетворення сили ваги NED -> trajectory
% -------------------------------------------------------------------------
% Оскільки сила ваги вже задана у NED, потрібен лише один перехід:
%
%       F_G_k = C_k_n * F_G_n.
%
% Очікувані компоненти:
%
%       [-m*g*sin(Theta);
%        -m*g*cos(Theta);
%         0].

F_G_k = simplify(C_k_n * F_G_n);

%% 18. Елементарна швидкісна матриця повороту навколо X
% -------------------------------------------------------------------------
% R_x_gamma_a задає поворот швидкісної системи навколо осі X_a,
% спрямованої вздовж вектора повітряної швидкості.
%
% Кут gamma_a — швидкісний кут крену.
% Це кут повороту осей Y_a і Z_a навколо поздовжньої осі X_a,
% яка збігається з напрямком вектора повітряної швидкості.

R_x_gamma_a = [1,                0,                 0;
               0,     cos(gamma_a),      sin(gamma_a);
               0,    -sin(gamma_a),      cos(gamma_a)];

%% 19. Елементарна швидкісна матриця повороту навколо Y
% -------------------------------------------------------------------------
% R_y_vartheta_a задає швидкісний кут тангажу vartheta_a.
%
% Він визначає вертикальний нахил вектора повітряної швидкості.

R_y_vartheta_a = [ cos(vartheta_a), 0, -sin(vartheta_a);
                                  0, 1,                 0;
                   sin(vartheta_a), 0,  cos(vartheta_a)];

%% 20. Елементарна швидкісна матриця повороту навколо Z
% -------------------------------------------------------------------------
% R_z_psi_a задає швидкісний кут рискання psi_a.
%
% Він визначає азимутальний напрям вектора повітряної швидкості.

R_z_psi_a = [ cos(psi_a),  sin(psi_a), 0;
             -sin(psi_a),  cos(psi_a), 0;
                       0,           0, 1];

%% 21. Матриця переходу NED -> швидкісну
% -------------------------------------------------------------------------
% Для узгодження з порядком матриць angles_ned.mlx використано:
%
%       D_a = R_x_gamma_a * R_y_vartheta_a * R_z_psi_a.
%
% Фізичний зміст:
%
%       vector_a = D_a * vector_n.
%
% Позначимо:
%
%       C_a_n = D_a.

D_a = simplify( ...
    R_x_gamma_a * R_y_vartheta_a * R_z_psi_a);

C_a_n = D_a;

%% 22. Матриця переходу aerodynamic -> NED
% -------------------------------------------------------------------------
% Зворотний перехід виконується транспонуванням:
%
%       vector_n = C_a_n.' * vector_a.

C_n_a = simplify(C_a_n.');

%% 23. Вектор аеродинамічних сил у швидкісній системі
% -------------------------------------------------------------------------
% У швидкісній системі:
%
%       -Q  — сила лобового опору проти осі +X_a;
%        Y_a — підйомна сила вздовж +Y_a;
%        Z_a — бокова сила вздовж +Z_a.
%
% Тому:
%
%       F_A_a = [-Q;Y_a;Z_a].

F_A_a = [-Q;
          Y_a;
          Z_a];

%% 24. Перетворення аеродинамічної сили aerodynamic -> NED
% -------------------------------------------------------------------------
% Початковий вектор задано у системі a.
%
% Перехід:
%
%       F_A_n = C_n_a * F_A_a.

F_A_n = simplify(C_n_a * F_A_a);

%% 25. Перетворення аеродинамічної сили NED -> trajectory
% -------------------------------------------------------------------------
% Другий перехід:
%
%       F_A_k = C_k_n * F_A_n.
%
% Разом:
%
%       F_A_k = C_k_n * C_n_a * F_A_a.
%
% Добуток C_k_n*C_n_a є матрицею aerodynamic -> trajectory.

C_k_a = simplify(C_k_n * C_n_a);
F_A_k = simplify(expand(C_k_a * F_A_a), 'Steps', 300);

%% 26. Сума всіх зовнішніх сил у trajectory
% -------------------------------------------------------------------------
% Після переведення всіх сил в одну систему координат їх можна складати:
%
%       F_total_k = F_P_k + F_G_k + F_A_k.
%
% Компоненти:
%
%       F_total_k(1) = F_xk;
%       F_total_k(2) = F_yk;
%       F_total_k(3) = F_zk.

F_total_k = simplify( ...
    expand(F_P_k + F_G_k + F_A_k), ...
    'Steps', 400);

%% 27. Формування рівняння (29)
% -------------------------------------------------------------------------
% Другий закон Ньютона у траєкторній системі:
%
%       m*a_k_expected = F_total_k.
%
% Покомпонентно:
%
%       m*dV_k/dt =
%           F_P_xk + F_G_xk + F_A_xk;
%
%       m*V_k*dTheta/dt =
%           F_P_yk + F_G_yk + F_A_yk;
%
%      -m*V_k*cos(Theta)*dPsi/dt =
%           F_P_zk + F_G_zk + F_A_zk.
%
% Ці три рівняння є компактною матричною формою рівняння (29).

eq29 = [m*a_k_expected(1) == F_total_k(1);
        m*a_k_expected(2) == F_total_k(2);
        m*a_k_expected(3) == F_total_k(3)];

%% 28. Групування правих частин за фізичними силами
% -------------------------------------------------------------------------
% expand(...) розкриває всі добутки.
%
% collect(...,[P,Q,Y_a,Z_a]) групує доданки за:
%
%       P   — тягою;
%       Q   — лобовим опором;
%       Y_a — підйомною силою;
%       Z_a — боковою силою.

rhs29_1 = collect( ...
    expand(F_total_k(1)), ...
    [P,Q,Y_a,Z_a]);

rhs29_2 = collect( ...
    expand(F_total_k(2)), ...
    [P,Q,Y_a,Z_a]);

rhs29_3 = collect( ...
    expand(F_total_k(3)), ...
    [P,Q,Y_a,Z_a]);

%% 29. Матриця коефіцієнтів при силах
% -------------------------------------------------------------------------
% Результуючу силу можна записати:
%
%       F_total_k =
%           A_force*[P;Q;Y_a;Z_a] + F_G_k.
%
% Стовпці A_force:
%
%       1 — коефіцієнти при P;
%       2 — коефіцієнти при Q;
%       3 — коефіцієнти при Y_a;
%       4 — коефіцієнти при Z_a.
%
% Рядки:
%
%       1 — проєкція на X_k;
%       2 — проєкція на Y_k;
%       3 — проєкція на Z_k.

force_variables = [P,Q,Y_a,Z_a];
A_force = sym(zeros(3,4));

for row_index = 1:3
    for column_index = 1:4
        A_force(row_index,column_index) = simplify( ...
            diff(F_total_k(row_index), ...
                 force_variables(column_index)), ...
            'Steps', 150);
    end
end



%% 30. Виведення основних матриць
disp('==============================================================')
disp('Матриця NED -> body, C_b_n = D:')
pretty(C_b_n)

disp('Матриця body -> NED, C_n_b = D.'':')
pretty(C_n_b)

disp('Матриця NED -> trajectory, C_k_n:')
pretty(C_k_n)

disp('Матриця body -> trajectory, C_k_b:')
pretty(C_k_b)

disp('Матриця NED -> aerodynamic, C_a_n = D_a:')
pretty(C_a_n)

disp('Матриця aerodynamic -> trajectory, C_k_a:')
pretty(C_k_a)

